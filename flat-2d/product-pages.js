const productOrder = Object.keys(PRODUCT_PAGES);

const PRODUCT_ASSET_VERSION = "20260608-bgfix-v1";

function versionAsset(src) {
  if (!src || !src.startsWith("./assets/") || src.includes("?")) return src;
  return `${src}?v=${PRODUCT_ASSET_VERSION}`;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function renderFacts(facts) {
  return facts
    .map(
      ([label, value]) => `
        <div class="pd-fact">
          <span class="pd-fact-label">${escapeHtml(label)}</span>
          <span class="pd-fact-value">${escapeHtml(value)}</span>
        </div>
      `
    )
    .join("");
}

function renderViews(views, compositeImage, title) {
  if (compositeImage) {
    return `
      <article class="pd-view-card pd-view-card--composite">
        <div class="pd-view-image pd-view-image--composite">
          <img src="${escapeHtml(versionAsset(compositeImage))}" alt="${escapeHtml(title)} front side top views" />
        </div>
      </article>
    `;
  }

  return views
    .map(
      ([label, src]) => `
        <article class="pd-view-card">
          <div class="pd-view-image"><img src="${escapeHtml(versionAsset(src))}" alt="${escapeHtml(label)} view" /></div>
          <div class="pd-view-label">${escapeHtml(label)}</div>
        </article>
      `
    )
    .join("");
}

function renderDimensions(dimensions, heroImage) {
  return dimensions
    .map(
      ([label, value]) => `
        <div class="pd-dimension-item">
          <span class="pd-dimension-label">${escapeHtml(label)}</span>
          <span class="pd-dimension-value">${escapeHtml(value)}</span>
        </div>
      `
    )
    .join("");
}

function renderDiagramSet(heroImage, diagramImage) {
  const src = diagramImage || heroImage;
  if (diagramImage) {
    return `
      <article class="pd-diagram-card pd-diagram-card--blueprint">
        <div class="pd-diagram-visual"><img src="${escapeHtml(versionAsset(src))}" alt="blueprint schematic" /></div>
      </article>
    `;
  }
  return ["Front", "Side", "Top"]
    .map(
      (label) => `
        <article class="pd-diagram-card">
          <div class="pd-diagram-visual"><img src="${escapeHtml(versionAsset(heroImage))}" alt="${escapeHtml(label)} schematic" /></div>
          <div class="pd-diagram-label">${escapeHtml(label)}</div>
        </article>
      `
    )
    .join("");
}

function renderEditorials(images, title) {
  return images
    .map(
      (src, index) => `
        <figure class="pd-editorial-card">
          <img src="${escapeHtml(versionAsset(src))}" alt="${escapeHtml(title)} editorial ${index + 1}" />
        </figure>
      `
    )
    .join("");
}

function renderTailVideo() {
  return `
    <section class="product-section pd-tail-video-stack pd-tail-video--fullbleed">
      <video class="pd-tail-video__media" autoplay muted loop playsinline preload="auto">
        <source src="./assets/about_lab_video.mp4?v=20260608-about-video-v1" type="video/mp4" />
      </video>
      <video class="pd-tail-video__media" autoplay muted loop playsinline preload="auto">
        <source src="./assets/thorn_mug_tail_video_02.mp4?v=20260608-mug-tail-video-02-v1" type="video/mp4" />
      </video>
    </section>
  `;
}

function renderPage(productId, level) {
  const product = PRODUCT_PAGES[productId];
  if (!product) return;

  const currentIndex = productOrder.indexOf(productId);
  const previousId = currentIndex > 0 ? productOrder[currentIndex - 1] : null;
  const nextId = currentIndex < productOrder.length - 1 ? productOrder[currentIndex + 1] : null;

  // 레벨이 지정된 경우 해당 레벨 이미지 사용 (파일명 규칙: {id의 -를 _로}_lv{N}.png)
  const assetPrefix = productId.replace(/-/g, "_");
  const levelImage = (level >= 1 && level <= 4)
    ? `./assets/${assetPrefix}_lv${level}.png`
    : null;
  const heroImage = levelImage || product.heroImage;
  const levelLabel = level ? `Lv.${level}` : null;

  // 레벨별 뷰 이미지: 레벨 이미지가 있으면 4장 모두 해당 이미지로
  const views = levelImage
    ? [["Front", levelImage], ["Side", levelImage], ["Top", levelImage], ["Detail", levelImage]]
    : product.views;
  const viewsCompositeImage = product.viewsCompositeImages?.[level] || null;
  const detailImage = product.lockDetailImageAcrossLevels
    ? product.detailImage
    : (levelImage || product.detailImage);
  const editorialImages = [
    ...(product.editorials || []),
    ...((level && product.editorialAppendByLevel?.[level]) || []),
  ];
  const shouldRenderTailVideo = productId === "thorn-mug" && level >= 1 && level <= 4;

  const titleSuffix = levelLabel ? ` — ${levelLabel}` : "";
  document.title = `${product.title}${titleSuffix} / Stress Gardening`;

  const mount = document.getElementById("productDetailApp");
  if (!mount) return;

  mount.innerHTML = `
    <main class="product-shell">
      <div class="product-frame">
        <section class="product-section pd-hero">
          <div class="pd-hero-index">${escapeHtml(product.index)}</div>
          <div class="pd-hero-copy">
            <div class="pd-collection">THORN COLLECTION</div>
            <h1 class="pd-title">${escapeHtml(product.title)}</h1>
            <div class="pd-subtitle">${escapeHtml(levelLabel ? `${levelLabel} / ${product.subtitle}` : product.subtitle)}</div>
            <p class="pd-lead">${escapeHtml(product.lead)}</p>
            <div class="pd-facts">${renderFacts(product.facts)}</div>
          </div>
          <div class="pd-hero-visual">
            <img src="${escapeHtml(versionAsset(heroImage))}" alt="${escapeHtml(product.title)}${levelLabel ? ` ${levelLabel}` : ""} hero image" />
          </div>
        </section>

        <section class="product-section pd-views">
          <div class="pd-views-index">02</div>
          ${renderViews(views, viewsCompositeImage, product.title)}
        </section>

        <section class="product-section pd-detail${product.detailSectionClass ? ` ${escapeHtml(product.detailSectionClass)}` : ""}">
          <div class="pd-detail-index">04</div>
          <div class="pd-detail-media">
            <img src="${escapeHtml(versionAsset(detailImage))}" alt="${escapeHtml(product.title)} detail" />
          </div>
          <div class="pd-detail-copy">
            <div class="pd-detail-text">
              <h2 class="pd-detail-title">${escapeHtml(product.detailTitle)}</h2>
              <p class="pd-detail-description">${escapeHtml(product.detailText)}</p>
            </div>
            <div class="pd-diagrams">
              <div class="pd-dimension-list">${renderDimensions(product.dimensions, heroImage)}</div>
              ${renderDiagramSet(heroImage, product.diagramImage)}
            </div>
          </div>
        </section>

        <section class="product-section pd-editorials${product.editorialsFullbleed ? " pd-editorials--fullbleed" : ""}">
          <div class="pd-editorials-index">06</div>
          <div class="pd-editorial-grid">${renderEditorials(editorialImages, product.title)}</div>
        </section>

        ${shouldRenderTailVideo ? renderTailVideo() : ""}

        <section class="pd-footer-nav">
          <a class="pd-back-link" href="./index.html?page=shop">&larr; Back to Shop</a>
          <div class="pd-nav-cluster">
            ${previousId ? `<a class="pd-nav-link" href="./${escapeHtml(previousId)}.html">Previous <strong>${escapeHtml(PRODUCT_PAGES[previousId].title)}</strong></a>` : ""}
            ${nextId ? `<a class="pd-nav-link" href="./${escapeHtml(nextId)}.html">Next <strong>${escapeHtml(PRODUCT_PAGES[nextId].title)}</strong></a>` : ""}
          </div>
        </section>
      </div>
    </main>
  `;
}

const productId = document.body.dataset.productId;
const urlLevel = parseInt(new URLSearchParams(window.location.search).get("level"), 10) || null;
renderPage(productId, urlLevel);
